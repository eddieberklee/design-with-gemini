'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const Client = require('./client.js');
const Renderer = require('./renderer.js');

test('pickFourModels selects 4 distinct Gemini multimodal models', () => {
  const picked = Client.pickFourModels([
    { name: 'models/gemini-2.5-pro', supportedGenerationMethods: ['generateContent'] },
    { name: 'models/gemini-2.5-flash', supportedGenerationMethods: ['generateContent'] },
    { name: 'models/gemini-2.5-flash-lite', supportedGenerationMethods: ['generateContent'] },
    { name: 'models/gemini-2.0-flash', supportedGenerationMethods: ['generateContent'] },
    { name: 'models/gemini-2.5-flash-image', supportedGenerationMethods: ['generateContent'] },
    { name: 'models/imagen-3.0-generate-002', supportedGenerationMethods: ['predict'] }
  ]);

  assert.equal(picked.length, 4);
  assert.equal(new Set(picked).size, 4);
  assert.deepEqual(picked, [
    'gemini-2.5-pro',
    'gemini-2.5-flash',
    'gemini-2.5-flash-lite',
    'gemini-2.0-flash'
  ]);
});

test('parse3DSceneFromText parses fenced JSON and sanitizes scales', () => {
  const scene = Client.parse3DSceneFromText([
    '```json',
    '{"title":"Mug","parts":[{"type":"cylinder","pos":[0,0,0],"rot":[0,0,0],"scale":[1,1.2,1],"color":"#cc5522"},{"type":"torus","pos":[0.6,0,0],"rot":[0,0,90],"scale":[0.4,0.4,0.2],"color":"#cc5522"}]}',
    '```'
  ].join('\n'));

  assert.equal(scene.title, 'Mug');
  assert.equal(scene.parts.length, 2);
  assert.equal(scene.parts[0].type, 'cylinder');
  assert.equal(scene.parts[1].type, 'torus');
});

test('buildMeshFromScene tessellates primitives and exportMeshToOBJ outputs valid OBJ', () => {
  const mesh = Renderer.buildMeshFromScene({
    title: 'Lamp',
    parts: [
      { type: 'cylinder', pos: [0, -0.5, 0], rot: [0, 0, 0], scale: [0.6, 0.2, 0.6], color: '#333333' },
      { type: 'cone', pos: [0, 0.4, 0], rot: [0, 0, 0], scale: [0.9, 0.6, 0.9], color: '#f4d35e' }
    ]
  });

  assert.equal(mesh.partCount, 2);
  assert.ok(mesh.vertices.length > 20);
  assert.ok(mesh.triangles.length > 20);

  const obj = Renderer.exportMeshToOBJ(mesh, 'Lamp');
  assert.match(obj, /^# Generated by Gemini Image-to-3D: Lamp/m);
  assert.match(obj, /^v /m);
  assert.match(obj, /^f /m);
});
